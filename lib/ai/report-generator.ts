// ==============================================================================
// GHOSTSHIELD: AI Investigation Report Generator
// Generates structured natural language narrative from verified graph evidence
// Supports AI Grants India (AIGI) / OpenAI endpoints with deterministic template fallback
// Authoritative score is never altered by LLM output
// ==============================================================================

import { RiskAssessment } from '@/lib/graph/types';

export interface AIReportResult {
  investigation_id: string;
  source: 'ai_llm' | 'deterministic_template';
  model_used?: string;
  generated_at: string;
  executive_summary: string;
  detailed_findings: string[];
  recommended_analyst_actions: string[];
  disclaimer: string;
}

export class AIReportGenerator {
  private apiKey?: string;
  private apiEndpoint?: string;
  private modelName: string;

  constructor() {
    this.apiKey = process.env.AIGI_API_KEY || process.env.OPENAI_API_KEY;
    this.apiEndpoint =
      process.env.AIGI_API_ENDPOINT || process.env.OPENAI_API_BASE || 'https://api.openai.com/v1/chat/completions';
    this.modelName = process.env.AIGI_MODEL || 'gpt-4o-mini';
  }

  public async generateReport(assessment: RiskAssessment): Promise<AIReportResult> {
    if (this.apiKey) {
      try {
        const aiResponse = await this.callAIEndpoint(assessment);
        if (aiResponse) {
          return aiResponse;
        }
      } catch (err) {
        console.warn('AI report generation failed, falling back to deterministic template:', err);
      }
    }

    return this.generateDeterministicTemplate(assessment);
  }

  private async callAIEndpoint(assessment: RiskAssessment): Promise<AIReportResult | null> {
    const prompt = {
      role: 'system',
      content: `You are GhostShield's Senior Security Graph Forensics Analyst.
Summarize the following verified graph evidence strictly from TigerGraph.
Rules:
1. Do not invent any addresses, timestamps, or amounts not present in the payload.
2. The risk score (${assessment.score}/100) and action (${assessment.action}) are authoritative; do NOT change them.
3. Distinguish proven graph topology from probabilistic risk.
4. Output valid JSON matching the format:
{
  "executive_summary": "...",
  "detailed_findings": ["finding 1", "finding 2"],
  "recommended_analyst_actions": ["action 1", "action 2"]
}`,
    };

    const userMessage = {
      role: 'user',
      content: JSON.stringify({
        investigationId: assessment.investigation_id,
        targetWallet: assessment.target_wallet,
        counterparty: assessment.counterparty,
        score: assessment.score,
        action: assessment.action,
        triggeredRules: assessment.contributing_rules.filter((r) => r.triggered),
        detectedCycles: assessment.detected_cycles,
        sharedFundingSources: assessment.shared_funding_sources,
        riskSeedExposure: assessment.risk_seed_exposure,
        missingDataWarnings: assessment.missing_data_warnings,
      }),
    };

    const res = await fetch(this.apiEndpoint!, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${this.apiKey}`,
      },
      body: JSON.stringify({
        model: this.modelName,
        messages: [prompt, userMessage],
        temperature: 0.1,
        response_format: { type: 'json_object' },
      }),
      signal: AbortSignal.timeout(6000),
    });

    if (!res.ok) {
      throw new Error(`AI API responded with HTTP ${res.status}`);
    }

    const data = await res.json();
    const content = data.choices?.[0]?.message?.content;
    if (!content) return null;

    const parsed = JSON.parse(content);

    return {
      investigation_id: assessment.investigation_id,
      source: 'ai_llm',
      model_used: this.modelName,
      generated_at: new Date().toISOString(),
      executive_summary: parsed.executive_summary || assessment.explanation,
      detailed_findings: parsed.detailed_findings || [],
      recommended_analyst_actions: parsed.recommended_analyst_actions || [],
      disclaimer:
        'This narrative synthesis is generated by AI based on verified TigerGraph topological evidence. Authoritative risk scoring is strictly deterministic.',
    };
  }

  private generateDeterministicTemplate(assessment: RiskAssessment): AIReportResult {
    const triggered = assessment.contributing_rules.filter((r) => r.triggered);
    const findings: string[] = [];
    const actions: string[] = [];

    if (assessment.action === 'REJECT') {
      findings.push(
        `Critical wash-trading or risk exposure detected: Score ${assessment.score}/100 exceeds rejection threshold (${DEFAULT_REJECT_THRESHOLD}).`
      );
    } else if (assessment.action === 'REVIEW') {
      findings.push(
        `Moderate risk detected: Score ${assessment.score}/100 falls in human review corridor.`
      );
    } else {
      findings.push(
        `Low risk confirmed: Score ${assessment.score}/100 within allowable bounds.`
      );
    }

    for (const rule of triggered) {
      findings.push(`[${rule.name}] ${rule.explanation}${rule.evidence_snippet ? ` (Evidence: ${rule.evidence_snippet})` : ''}`);
    }

    if (assessment.detected_cycles.length > 0) {
      const c = assessment.detected_cycles[0];
      findings.push(
        `Directed cyclic path: ${c.cycle_path} traversed in ${c.duration_seconds} seconds with ${(c.volume_retention * 100).toFixed(1)}% volume retention.`
      );
    }

    if (assessment.missing_data_warnings.length > 0) {
      findings.push(`Data Caveats: ${assessment.missing_data_warnings.join(' ')}`);
    }

    if (assessment.action === 'REJECT') {
      actions.push('Block simulated transaction execution at protocol gateway.');
      actions.push('Flag connected cluster wallets for automated forensic monitoring.');
      actions.push('Dispatch automated alert to compliance team via configured webhook.');
    } else if (assessment.action === 'REVIEW') {
      actions.push('Assign ticket to Tier-2 security analyst for manual graph path verification.');
      actions.push('Inspect counterparty wallet deposit history on target network explorer.');
    } else {
      actions.push('Allow candidate transaction to proceed through standard protocol pipeline.');
      actions.push('Log clean graph traversal evidence to telemetry store.');
    }

    return {
      investigation_id: assessment.investigation_id,
      source: 'deterministic_template',
      generated_at: new Date().toISOString(),
      executive_summary: `GhostShield Forensic Synthesis: Target ${assessment.target_wallet} assessed at risk score ${assessment.score}/100 (${assessment.action}). Analysis generated via deterministic graph rule evaluation.`,
      detailed_findings: findings,
      recommended_analyst_actions: actions,
      disclaimer:
        'Evidence compiled deterministically from active graph traversal. Zero hallucination guarantee.',
    };
  }
}

const DEFAULT_REJECT_THRESHOLD = 65;
export const defaultAIReportGenerator = new AIReportGenerator();
