// ==============================================================================
// GHOSTSHIELD: Scale ladder
//   tsx scripts/scale_test.ts [--stages 100000,125000] [--per-wallet 4] [--start 2000]
// Adds server-side synthetic benign traffic (ghostshield_synth_amplify) in stages
// and, after each stage, re-runs every detector against the planted ground truth
// and records latency. Writes docs/SCALE.md. Existing synth wallets are never
// duplicated: indices continue from --start.
// ==============================================================================

import * as fs from 'fs';
import * as path from 'path';
import { cycles, clusters, propagation, latencies, SCOPE } from './evaluate_live';
import { runQuery } from './lib/tg';

const arg = (name: string, fallback: string) => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : fallback;
};

const stages = arg('stages', '100000,125000').split(',').map(Number);
const perWallet = Number(arg('per-wallet', '4'));
let nextIndex = Number(arg('start', '2000'));
const BATCH = 10_000;

const pct = (n: number, d: number) => (d === 0 ? 'n/a' : `${((100 * n) / d).toFixed(1)}%`);

async function counts() {
  const m: any = Object.assign({}, ...(await runQuery('ghostshield_dashboard_metrics', { scope: SCOPE }, 150)).results);
  return { wallets: m.total_wallets as number, transfers: m.total_transfers as number };
}

async function amplify(wallets: number) {
  const t0 = Date.now();
  for (let done = 0; done < wallets; done += BATCH) {
    const n = Math.min(BATCH, wallets - done);
    await runQuery('ghostshield_synth_amplify', { first_index: nextIndex, wallet_count: n, transfers_per_wallet: perWallet, hubs: 300 }, 120);
    nextIndex += n;
    process.stdout.write(`  inserted ${done + n}/${wallets} wallets\r`);
  }
  console.log(`  insert took ${((Date.now() - t0) / 1000).toFixed(0)}s                    `);
}

async function measure(label: string) {
  const size = await counts();
  console.log(`\n== ${label}: ${size.wallets.toLocaleString()} wallets, ${size.transfers.toLocaleString()} transfers`);
  const out: Record<string, any> = { label, ...size };
  try {
    const c = await cycles();
    const s = await clusters();
    const p = await propagation();
    const lat = await latencies();
    out.cycles = { precision: c.precision, recall: c.recall, slowFlagged: c.slowFlagged, p50: c.p50, p95: c.p95 };
    out.sybil = { precision: s.precision, recall: s.recall, memberFp: s.memberFp, p50: s.p50, p95: s.p95 };
    out.taint = { hitsAtK: p.hitsAtK, k: p.k, p50: p.p50, p95: p.p95 };
    out.lat = lat;
    console.log(`  cycles  P ${pct(c.tp, c.tp + c.fp)} R ${pct(c.tp, c.tp + c.fn)} slow-flagged ${c.slowFlagged}  p50 ${c.p50}ms p95 ${c.p95}ms`);
    console.log(`  sybil   P ${pct(s.clusterTp, s.clusterTp + s.clusterFp)} R ${pct(s.farmsFound, s.farms)} member-FP ${s.memberFp}  p50 ${s.p50}ms`);
    console.log(`  taint   ${p.hitsAtK}/${p.k} at top-k  p50 ${p.p50}ms`);
  } catch (e: any) {
    out.error = e.message;
    console.log(`  FAILED at this size: ${e.message.slice(0, 200)}`);
  }
  return out;
}

async function main() {
  const rows: any[] = [];
  rows.push(await measure('baseline'));
  let added = 0;
  for (const stage of stages) {
    console.log(`\nadding ${stage.toLocaleString()} wallets x ${perWallet} transfers server-side...`);
    await amplify(stage);
    added += stage;
    rows.push(await measure(`+${added.toLocaleString()} synthetic wallets`));
    fs.writeFileSync(path.resolve(process.cwd(), 'data/generated/scale_rows.json'), JSON.stringify(rows));
  }

  const f = (x: number) => `${(100 * x).toFixed(1)}%`;
  const md = `# Scale ladder

Generated by \`npm run scale:live\` on ${new Date().toISOString().slice(0, 10)}, TigerGraph Savanna TG-00 (16Gi, smallest tier).
The planted ground truth (13 rings, 40 slow decoys, 8 farms, taint chains, exchange crowds, bot fleets) stays fixed; each stage adds
benign random transfers generated **inside the engine** (\`ghostshield_synth_amplify\`, hub-biased targets, timestamps over 90 days).
So each row asks: does detection quality hold, and what does latency do, when the haystack grows?

| Graph size | Cycles P / R | Slow decoys flagged | Sybil P / R | Taint top-k | Cycles p50 / p95 | Sybil p50 | Taint p50 |
|---|---|---|---|---|---|---|---|
${rows.map((r) => (r.error ? `| ${r.wallets?.toLocaleString()} wallets, ${r.transfers?.toLocaleString()} transfers | FAILED: ${String(r.error).slice(0, 80)} | | | | | | |` : `| ${r.wallets.toLocaleString()} wallets, ${r.transfers.toLocaleString()} transfers | ${f(r.cycles.precision)} / ${f(r.cycles.recall)} | ${r.cycles.slowFlagged}/40 | ${f(r.sybil.precision)} / ${f(r.sybil.recall)} | ${r.taint.hitsAtK}/${r.taint.k} | ${r.cycles.p50} / ${r.cycles.p95} ms | ${r.sybil.p50} ms | ${r.taint.p50} ms |`)).join('\n')}

Latency includes the internet round trip. Added wallets are benign by construction, so a precision drop means chance
coincidences in noise (the realistic failure mode), not mislabelled fraud.

Caveat: the added noise wallets have transfers only (no funding or control edges), so Sybil quality cannot change with scale by construction;
for Sybil and taint the informative columns are latency. Cycle precision holding is the real signal: with timestamps spread over 90 days,
chance 10-minute round trips stay rare even at ~1M transfers.
`;
  fs.writeFileSync(path.resolve(process.cwd(), 'docs/SCALE.md'), md);
  console.log('\nwrote docs/SCALE.md');
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
